function ResultPanel({ attempt, session, language, onRetry, onNew }: { attempt: QuizAttempt; session?: LearningSession; language: 'ar' | 'en'; onRetry: () => void; onNew: () => void }) {
  const t = copy[language];
  const label = attempt.mastery >= 80 ? t.mastered : attempt.mastery >= 60 ? t.developing : t.revisit;
  const Arrow = language === 'ar' ? ArrowLeft : ArrowRight;
  const Back = language === 'ar' ? ChevronRight : ChevronLeft;
  return <div className="mx-auto max-w-5xl space-y-6"><section className="assessment-result"><div className="assessment-result-heading"><div className="flex items-center gap-2 text-xs font-black"><ShieldCheck className="h-5 w-5" />{t.result}</div><h1>{label}</h1><p>{attempt.topic}</p><div className="assessment-result-metrics"><ResultMetric label={t.score} value={`${attempt.score}/${attempt.total}`} /><ResultMetric label={t.mastery} value={`${attempt.mastery}%`} /><ResultMetric label={t.resultEvidence} value={session ? '1' : '—'} /></div></div><div className="assessment-result-body"><h2>{t.skill}</h2><p>{t.resultEvidenceBody}</p><div className="mt-4 grid gap-2 sm:grid-cols-2">{attempt.skills.map((skill, index) => <div key={`${skill.skill}-${index}`} className={`flex items-center gap-3 rounded-2xl border p-3 text-xs font-bold ${skill.correct ? 'border-teal-200 bg-teal-50 text-teal-900 dark:border-teal-400/20 dark:bg-teal-500/10 dark:text-teal-100' : 'border-amber-200 bg-amber-50 text-amber-950 dark:border-amber-400/20 dark:bg-amber-500/10 dark:text-amber-100'}`}>{skill.correct ? <CheckCircle2 className="h-4 w-4 shrink-0" /> : <AlertCircle className="h-4 w-4 shrink-0" />}{skill.skill}</div>)}</div><div className="mt-7 flex flex-col gap-3 sm:flex-row"><button type="button" onClick={onRetry} className="premium-button justify-center"><RotateCcw className="h-4 w-4" />{t.retry}<Arrow className="h-4 w-4" /></button><button type="button" onClick={onNew} className="premium-button-secondary justify-center"><Back className="h-4 w-4" />{t.newTopic}</button></div></div></section><LearningEvidencePanel session={session} language={language} /></div>;
}

function ResultMetric({ label, value }: { label: string; value: string }) {
  return <div><p>{label}</p><strong>{value}</strong></div>;
}
